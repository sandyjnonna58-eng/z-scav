function PANEL:OnMousePressed(code)
    if code == MOUSE_LEFT then
        local mx, my = self:CursorPos()
        do
            local x, y, w, h = self:SleepRect()
            if mx >= x and mx <= x + w and my >= y and my <= y + h then
                if self:SleepState(self:GetOrg()) then
                    net.Start("zscav_sleep") net.WriteBool(true) net.SendToServer()
                    surface.PlaySound("ui/rem_select.wav")
                    self:Close()
                else
                    surface.PlaySound("ui/rem_hover.wav")
                end
                return
            end
        end
        local ii = self:ItemAt(mx, my)
        if ii then
            local id = self.Items[ii].id
            self.SelItemId = (self.SelItemId == id) and nil or id
            surface.PlaySound("ui/rem_hover.wav")
            return
        end
        if self.Hover then
            if self.SelItemId then
                self:UseOn(self.Hover)
            else
                self.Selected = self.Hover
                surface.PlaySound("ui/rem_select.wav")
            end
        end
    elseif code == MOUSE_RIGHT then
        if self.SelItemId then self.SelItemId = nil return end
        self:Close()
    end
end

