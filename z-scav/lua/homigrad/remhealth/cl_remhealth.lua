local function PartState(org, i, wnd)
    local p = PARTS[i]
    local woundShardF
    local lines = {}
    local function add(text, col) lines[#lines + 1] = {text, col or C_GREEN} end
    local bone, organ = 0, 0
    local missing = false

    if p.limb then
        bone = N(org[p.limb])
        missing = org[p.limb .. "amputated"] == true
        if missing then add("АМПУТИРОВАНО", C_RED) end
        if bone >= 1 then add("ПЕРЕЛОМ", C_RED)
        elseif bone > 0 then add(("КОСТЬ ПОВРЕЖДЕНА %d%%"):format(bone * 100), C_YELLOW) end
        if org[p.limb .. "dislocation"] then add("ВЫВИХ  (РУКИ -> вправить)", C_ORANGE) end
    elseif p.id == "head" then
        bone = N(org.skull)
        organ = N(org.brain)
        missing = org.headamputated == true
        if bone >= 1 then add("ПЕРЕЛОМ ЧЕРЕПА", C_RED) elseif bone > 0 then add(("ЧЕРЕП %d%%"):format((1 - bone) * 100), C_YELLOW) end
        add(("МОЗГ %d%%"):format((1 - organ) * 100), HealthColor(1 - organ))
        if N(org.brainHemorrhage) > 0 then add("КРОВОИЗЛИЯНИЕ В МОЗГ", C_RED) end
        local eL, eR = N(org.eyeL), N(org.eyeR)
        if org.eyePoppedL or org.eyePoppedR then add("ГЛАЗ ВЫБИТ", C_RED)
        elseif eL > 0 or eR > 0 then add(("ГЛАЗА  П %d%%  Л %d%%"):format((1 - eR) * 100, (1 - eL) * 100), C_YELLOW) end
        if org.jawdislocation then add("ВЫВИХ ЧЕЛЮСТИ", C_ORANGE) end
        if N(org.jaw) >= 1 then add("ПЕРЕЛОМ ЧЕЛЮСТИ", C_RED) end
    elseif p.id == "neck" then
        bone = N(org.spine3)
        organ = N(org.trachea)
        if bone >= 1 then add("ПЕРЕЛОМ ШЕЙНОГО ОТДЕЛА", C_RED) elseif bone > 0 then add(("ПОЗВОНОЧНИК %d%%"):format((1 - bone) * 100), C_YELLOW) end
        if organ > 0 then add(("ТРАХЕЯ %d%%"):format((1 - organ) * 100), HealthColor(1 - organ)) end
    elseif p.id == "chest" then
        bone = math.max(N(org.chest), N(org.spine2))
        local lL, lR = Lung(org.lungsL), Lung(org.lungsR)
        organ = math.max(N(org.heart), lL, lR)
        if N(org.chest) >= 1 then add("ПЕРЕЛОМ РЁБЕР", C_RED) elseif N(org.chest) > 0 then add(("РЁБРА %d%%"):format((1 - N(org.chest)) * 100), C_YELLOW) end
        if N(org.spine2) > 0 then add(("ПОЗВОНОЧНИК %d%%"):format((1 - N(org.spine2)) * 100), HealthColor(1 - N(org.spine2))) end
        add(("СЕРДЦЕ %d%%"):format((1 - N(org.heart)) * 100), HealthColor(1 - N(org.heart)))
        add(("ЛЁГКИЕ  П %d%%  Л %d%%"):format((1 - lR) * 100, (1 - lL) * 100), HealthColor(1 - math.max(lL, lR)))
        if N(org.pneumothorax) > 0 then add("ПНЕВМОТОРАКС", C_RED) end
    elseif p.id == "abdomen" then
        bone = math.max(N(org.pelvis), N(org.spine1))
        organ = math.max(N(org.liver), N(org.stomach), N(org.intestines))
        if N(org.pelvis) >= 1 then add("ПЕРЕЛОМ ТАЗА", C_RED) elseif N(org.pelvis) > 0 then add(("ТАЗ %d%%"):format((1 - N(org.pelvis)) * 100), C_YELLOW) end
        if N(org.spine1) > 0 then add(("ПОЯСНИЦА %d%%"):format((1 - N(org.spine1)) * 100), HealthColor(1 - N(org.spine1))) end
        add(("ПЕЧЕНЬ %d%%"):format((1 - N(org.liver)) * 100), HealthColor(1 - N(org.liver)))
        add(("ЖЕЛУДОК %d%%"):format((1 - N(org.stomach)) * 100), HealthColor(1 - N(org.stomach)))
        add(("КИШЕЧНИК %d%%"):format((1 - N(org.intestines)) * 100), HealthColor(1 - N(org.intestines)))
        if N(org.internalBleed) > 0 then add("ВНУТРЕННЕЕ КРОВОТЕЧЕНИЕ", C_RED) end
    end

    if wnd.arterial > 0 then add("АРТЕРИАЛЬНОЕ КРОВОТЕЧЕНИЕ", C_RED) end
    if wnd.count > 0 then
        add(("РАНЫ: %d  (кровопотеря %.1f)"):format(wnd.count, wnd.amount), wnd.amount > 5 and C_ORANGE or C_YELLOW)
    end
    -- осколки
    local shards, glass = 0, 0
    for _, sh in ipairs(RemShardList()) do
        if sh.part == p.id then
            shards = shards + 1
            if sh.kind == "glass" then glass = glass + 1 end
        end
    end
    if shards > 0 then
        local kinds = glass == shards and " стекло" or (glass > 0 and (" (стекло %d)"):format(glass) or "")
        add(("ОСКОЛКИ: %d%s  (РУКИ -> нажать сюда)"):format(shards, kinds), C_ORANGE)
        woundShardF = math.min(shards * 0.15, 0.5)
    end
    -- кожа и инфекция
    local skin, infect = RemSkin(p.id)
    if skin < 0.995 then add(("КОЖА %d%%"):format(skin * 100), HealthColor(skin)) end
    if infect > 0.005 then add(("ИНФЕКЦИЯ %d%%"):format(infect * 100), Blink(3) and C_RED or C_ORANGE) end
    if #lines == 0 then add("ПОВРЕЖДЕНИЙ НЕТ", C_DIM) end

    local woundF = math.Clamp(wnd.amount / 20, 0, 1) * 0.6 + (wnd.arterial > 0 and 0.5 or 0) + (woundShardF or 0)
    local skinNow, infectNow = RemSkin(p.id)
    local health = 1 - math.max(bone, organ, woundF, (1 - skinNow) * 0.8, infectNow)
    if missing then health = 0 end

    -- боль этой части (0..100): переломы, вывихи, раны, осколки, органы.
    -- Общая боль организма усиливает/ослабляет (обезболивающие - меньше дрожь)
    local partPain = 0
    if not missing then
        partPain = math.Clamp(bone, 0, 1) * 70 + organ * 40
            + math.min(wnd.amount * 3, 40) + (wnd.arterial > 0 and 30 or 0)
            + shards * 15
            + ((p.limb and org[p.limb .. "dislocation"]) and 45 or 0)
            + ((p.id == "head" and org.jawdislocation) and 30 or 0)
            + (1 - skinNow) * 15 + infectNow * 25
        local g = math.Clamp(N(org.pain) / 30, 0.25, 1.6)
        partPain = math.Clamp(partPain * g, 0, 100)
    end

    return {
        pain = partPain,
        health = math.Clamp(health, 0, 1),
        bone = 1 - math.Clamp(bone, 0, 1),
        flesh = 1 - math.Clamp(woundF, 0, 1),
        skin = skin,
        infect = infect,
        bleeding = wnd.count > 0 or wnd.arterial > 0,
        missing = missing,
        lines = lines,
    }
end

