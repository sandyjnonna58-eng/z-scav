    -- затемнение мира
    surface.SetDrawColor(0, 0, 0, 170)
    surface.DrawRect(0, 0, w, h)

    local org = self:GetOrg()
    local mx, my, mw = S(26), S(26), S(430)
    local mh = self:DrawMonitor(org, mx, my, mw)

    if org then
        self:DrawPartCard(self.Hover or self.Selected, mx, my + mh + S(24), mw)
    end

    self:DrawDoll()
    self:DrawItems()
    self:DrawSleepButton(org)

    Txt("ЛКМ - выбрать часть / предмет -> часть   ПКМ / " .. string.upper(input.GetKeyName(KEY_CVAR:GetInt()) or "?") .. " / ESC - закрыть",
        "RemHP_Small", w - S(20), h - S(16), C_DIM, TEXT_ALIGN_RIGHT, TEXT_ALIGN_BOTTOM)
end

