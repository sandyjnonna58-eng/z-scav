    self:DrawDrops()
end

vgui.Register("RemHealthMenu", PANEL, "EditablePanel")

-- ---------------------------------------------------------------------------
-- открытие / закрытие
-- ---------------------------------------------------------------------------
function hg.ToggleHealthMenu()
    if IsValid(hg.RemHealthPanel) then
        hg.RemHealthPanel:Close()
        return
    end
    local ply = LocalPlayer()
    if not IsValid(ply) or not ply:Alive() then return end
    if IsValid(MainMenu) then return end

    local pnl = vgui.Create("RemHealthMenu")
    pnl:MakePopup()
    pnl:SetKeyboardInputEnabled(false) -- клавиатура остаётся игре: можно закрыть той же клавишей
    hg.RemHealthPanel = pnl
end

concommand.Add("rem_health", function() hg.ToggleHealthMenu() end)

hook.Add("PlayerButtonDown", "RemHealth_Key", function(ply, key)
    if ply ~= LocalPlayer() or not IsFirstTimePredicted() then return end
    if key ~= KEY_CVAR:GetInt() then return end
    if vgui.GetKeyboardFocus() or gui.IsGameUIVisible() then return end
    hg.ToggleHealthMenu()
end)

-- ESC закрывает меню здоровья, а не открывает главное меню
hook.Add("OnShowZCityPause", "RemHealth_Esc", function()
    if IsValid(hg.RemHealthPanel) then
        hg.RemHealthPanel:Close()
        return false
    end
end)
