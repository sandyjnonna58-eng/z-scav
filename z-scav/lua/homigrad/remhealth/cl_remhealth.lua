-- сила кровотечения части -> уровень капли 0..8 (0 - не кровит)
local function DropLevel(wnd)
    if not wnd then return 0 end
    local amount = (wnd.amount or 0) + (wnd.arterial or 0) * 25
    if amount <= 0.05 and (wnd.count or 0) == 0 then return 0 end
    -- примерно: царапина 1-2, обычная рана 3-5, сильная 6-7, артерия 8
    local lvl = math.ceil(math.Clamp(math.sqrt(amount / 0.4), 1, 8))
    if (wnd.arterial or 0) > 0 then lvl = 8 end
    return lvl
end
hg.RemDropLevel = DropLevel

