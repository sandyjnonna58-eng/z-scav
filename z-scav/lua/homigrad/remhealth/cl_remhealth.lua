function PANEL:DollRect()
    local h = math.min(ScrH() * 0.86, S(900))
    local w = h * DOLL_W / DOLL_H
    local x = ScrW() * 0.64 - w * 0.5
    local y = (ScrH() - h) * 0.5
    return x, y, w, h
end

function PANEL:Think()
    local ply = LocalPlayer()
    if not IsValid(ply) or not ply:Alive() then self:Close() return end

    local now = RealTime()
    local dt = math.min(now - self.Last, 0.1)
    self.Last = now

    PickDoll()

    if (self.nextItems or 0) < now then
        self.nextItems = now + 0.5
        self:RefreshItems()
    end

    local org = self:GetOrg()
    if org then
        ECGStep(self.ECG, dt, org)
        self.Wounds = CollectWounds(ply)
        for i = 1, #PARTS do self.States[i] = PartState(org, i, self.Wounds[i]) end
    end

    -- наведение на куклу
    local x, y, w, h = self:DollRect()
    local mx, my = self:CursorPos()
    local hov
    if self.AvatarDrawn then
        hov = AvatarPartAt(mx, my, self.States)
    elseif mx >= x and mx <= x + w and my >= y and my <= y + h then
        hov = PartAt((mx - x) / w * DOLL_W, (my - y) / h * DOLL_H)
    end
    if hov ~= self.Hover and hov then surface.PlaySound("ui/rem_hover.wav") end
    self.Hover = hov
    self:SetCursor(hov and "hand" or "arrow")
end

