-- раны по частям тела
local function CollectWounds(ply)
    local res = {}
    for i = 1, #PARTS do res[i] = {count = 0, amount = 0, arterial = 0} end
    local function bonePart(b)
        if isnumber(b) then b = ply:GetBoneName(b) end
        return b and PART_BY_BONE[b]
    end
    local wounds = ply.GetNetVar and ply:GetNetVar("wounds", {}) or {}
    for _, w in ipairs(istable(wounds) and wounds or {}) do
        local pi = bonePart(w[4])
        if pi then
            res[pi].count = res[pi].count + 1
            res[pi].amount = res[pi].amount + N(w[1])
        end
    end
    local art = ply.GetNetVar and ply:GetNetVar("arterialwounds", {}) or {}
    for _, w in ipairs(istable(art) and art or {}) do
        local pi = bonePart(w[4])
        if pi then res[pi].arterial = res[pi].arterial + 1 end
    end
    return res
end

