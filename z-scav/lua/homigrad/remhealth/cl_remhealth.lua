-- ---- кукла -----------------------------------------------------------------
function PANEL:DrawDoll()
    local x, y, w, h = self:DollRect()
    local t = RealTime()

    -- дрожь части от боли: чем сильнее боль, тем сильнее и чаще трясёт
    local function Shake(i, st)
        local pain = st and st.pain or 0
        if pain < 3 then return 0, 0 end
        local k = (pain / 100) ^ 1.2
        local amp = S(0.6 + 7 * k)
        local fr = 9 + 16 * k
        local ph = i * 1.7
        return math.sin(t * fr + ph) * amp + math.sin(t * fr * 2.3 + ph * 3) * amp * 0.35,
               math.cos(t * fr * 0.9 + ph) * amp * 0.7 + math.sin(t * fr * 1.7 + ph) * amp * 0.25
    end
    local offs = {}
    for i, p in ipairs(PARTS) do
        local ox, oy = Shake(i, self.States[i])
        offs[i] = {ox, oy}
    end

    -- цвет подсветки части: состояние, кровотечение, выбор, наведение
    local function PartColor(i)
        local st = self.States[i]
        local a, col = 0, C_GREEN
        if st then
            if st.missing then
                col, a = Color(10, 10, 10), 230
            elseif st.health < 0.999 then
                col = HealthColor(st.health)
                a = 90 + (1 - st.health) * 140
            end
            if st.bleeding and not st.missing then
                -- пульсирует красным, если кровоточит
                local pulse = 0.5 + 0.5 * math.sin(t * 6)
                col = Color(255, 40 + 40 * pulse, 40)
                a = math.max(a, 120 + 100 * pulse)
            end
        end
        if i == self.Selected then
            a = math.max(a, 70)
            if a == 70 then col = C_GREEN end
        end
        if i == self.Hover then
            a = math.min(255, a + 60)
            if not st or st.health >= 0.999 then col = C_GREEN end
        end
        return col, a
    end

    -- аватар: твоя модель чёрным силуэтом (дрожь делают сами кости)
    local CENTERS = PART_CENTER
    self.AvatarDrawn = AvatarOn() and AvatarDraw(self, LocalPlayer(), x, y, w, h, self.States, function(i) return offs[i][1], offs[i][2] end) or false
    if self.AvatarDrawn then
        AvatarPaintParts(PartColor)
        CENTERS = AV.centers
        for i = 1, #PARTS do offs[i] = {0, 0} end
    end

    -- части: заливка + контур
    surface.SetDrawColor(255, 255, 255, 255)
    local split = PARTS[1].full and not PARTS[1].full:IsError()
    if self.AvatarDrawn then
        -- уже нарисовано
    elseif split then
        for i, p in ipairs(PARTS) do
            local st = self.States[i]
            if not (st and st.missing) then
                surface.SetMaterial(p.full)
                surface.DrawTexturedRect(x + offs[i][1], y + offs[i][2], w, h)
            end
        end
    else
        -- запасной вариант: цельная кукла (если файлов частей нет)
        surface.SetMaterial(matOutline) surface.DrawTexturedRect(x, y, w, h)
        surface.SetMaterial(matDoll)    surface.DrawTexturedRect(x, y, w, h)
    end

    for i, p in ipairs(PARTS) do
        if self.AvatarDrawn then break end
        local col, a = PartColor(i)
        if a > 0 then
            surface.SetDrawColor(col.r, col.g, col.b, a)
            surface.SetMaterial(p.mat)
            surface.DrawTexturedRect(x + offs[i][1], y + offs[i][2], w, h)
        end
    end

    -- белые линии поверх (дрожат вместе с частью)
    surface.SetDrawColor(255, 255, 255, 255)
    if self.AvatarDrawn then
        -- у силуэта линий нет: контур уже белый
    elseif split and PARTS[1].plines and not PARTS[1].plines:IsError() then
        for i, p in ipairs(PARTS) do
            local st = self.States[i]
            if not (st and st.missing) then
                surface.SetMaterial(p.plines)
                surface.DrawTexturedRect(x + offs[i][1], y + offs[i][2], w, h)
            end
        end
    else
        surface.SetMaterial(matLines)
        surface.DrawTexturedRect(x, y, w, h)
    end

    -- капли крови рисуются в самом конце Paint, поверх всего (PANEL:DrawDrops)
    self.DropCtx = {x = x, y = y, w = w, h = h, offs = offs, centers = CENTERS}

    -- осколки в теле
    local org = self:GetOrg()
    if org then
        local per = {}
        for _, sh in ipairs(RemShardList()) do
            local c = CENTERS[sh.part]
            if c then
                per[sh.part] = (per[sh.part] or 0) + 1
                local n = per[sh.part]
                local sx = x + (c[1] + ((n - 1) * 0.025 - 0.01) * DOLL_W) / DOLL_W * w
                local sy = y + (c[2] - 0.035 * DOLL_H) / DOLL_H * h
                local sh_h = S(46)
                surface.SetDrawColor(255, 255, 255, 255)
                surface.SetMaterial(matShard)
                surface.DrawTexturedRectRotated(sx, sy, sh_h * 125 / 683, sh_h, 18 - n * 12)
            end
        end
    end

    -- подпись части под курсором
    if self.Hover then
        local mx, my = self:CursorPos()
        local st = self.States[self.Hover]
        local label = PARTS[self.Hover].name
        if st then label = label .. ("  %d%%"):format(st.health * 100) end
        surface.SetFont("RemHP_Med")
        local tw, th = surface.GetTextSize(label)
        local bx, by = mx + S(18), my + S(10)
        surface.SetDrawColor(C_BG) surface.DrawRect(bx - S(6), by - S(4), tw + S(12), th + S(8))
        surface.SetDrawColor(C_DIM) surface.DrawOutlinedRect(bx - S(6), by - S(4), tw + S(12), th + S(8), 1)
        Txt(label, "RemHP_Med", bx, by, st and HealthColor(st.health) or C_GREEN)
    end
end

-- кровотечение: капля на каждой кровоточащей части (чем сильнее, тем больше и краснее).
-- Рисуется последней - поверх куклы/аватара, предметов, кнопок и подписей.
function PANEL:DrawDrops()
    local ctx = self.DropCtx
    if not ctx then return end
    local x, y, w, h, offs, CENTERS = ctx.x, ctx.y, ctx.w, ctx.h, ctx.offs, ctx.centers
    render.SetStencilEnable(false)
    DisableClipping(true)
    for i, p in ipairs(PARTS) do
        local lvl = DropLevel(self.Wounds and self.Wounds[i])
        local c = CENTERS[p.id]
        if lvl > 0 and c and matDrops[lvl] and not matDrops[lvl]:IsError() then
            local size = S(16 + lvl * 5)
            -- капля "стекает": медленно сползает вниз и снова появляется
            local ph = (RealTime() * (0.4 + lvl * 0.08) + i * 0.37) % 1
            local sx = x + (c[1] / DOLL_W) * w + offs[i][1] + S(10)
            local sy = y + (c[2] / DOLL_H) * h + offs[i][2] - S(6) + ph * S(10)
            local a = 255 * math.min(1, (1 - ph) * 3)
            surface.SetDrawColor(255, 255, 255, a)
            surface.SetMaterial(matDrops[lvl])
            surface.DrawTexturedRect(sx - size * 0.5, sy - size * 0.5, size, size)
        end
    end
    DisableClipping(false)
end

