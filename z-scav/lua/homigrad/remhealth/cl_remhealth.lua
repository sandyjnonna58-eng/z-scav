local ECG_RATE = 90   -- точек в секунду
local ECG_LEN  = 270  -- 3 секунды на экране

local function ECGShape(ph)
    -- P - QRS - T
    local function g(c, w, a) return a * math.exp(-((ph - c) / w) ^ 2) end
    return g(0.12, 0.035, 0.15) - g(0.27, 0.012, 0.15) + g(0.30, 0.014, 1.0) - g(0.33, 0.014, 0.3) + g(0.55, 0.06, 0.3)
end

local function ECGStep(st, dt, org)
    st.acc = (st.acc or 0) + dt * ECG_RATE
    -- org.pulse в гейммоде - это скорее давление, частота сердца - org.heartbeat
    local pulse = N(org.heartbeat, N(org.pulse, 70))
    local dead = org.heartstop or org.alive == false or N(org.pulse, 70) < 5
    while st.acc >= 1 do
        st.acc = st.acc - 1
        local v
        if dead then
            v = (math.random() - 0.5) * 0.02
        elseif org.fibrillation and org.fibrillation ~= 0 and org.fibrillation ~= false then
            st.fib = (st.fib or 0) + 0.35 + math.random() * 0.25
            v = math.sin(st.fib) * 0.25 + math.sin(st.fib * 2.7) * 0.12 + (math.random() - 0.5) * 0.08
        else
            local rate = pulse / 60 / ECG_RATE
            local arr = isnumber(org.arrhythmia) and org.arrhythmia or 0
            if arr > 0.1 then
                -- чем сильнее аритмия, тем сильнее "скачет" ритм
                rate = rate * math.max(0.15, 1 + (math.random() - 0.4) * 1.6 * arr)
            end
            st.phase = ((st.phase or 0) + rate) % 1
            v = ECGShape(st.phase) + (math.random() - 0.5) * 0.03
        end
        st.buf = st.buf or {}
        st.buf[#st.buf + 1] = v
        if #st.buf > ECG_LEN then table.remove(st.buf, 1) end
    end
end

local function DrawECG(st, x, y, w, h)
    local buf = st.buf
    if not buf or #buf < 2 then return end
    local n = #buf
    local mid = y + h * 0.62
    local amp = h * 0.55
    local px, py
    for i = 1, n do
        local cx = x + (i - 1) / (ECG_LEN - 1) * w
        local cy = mid - buf[i] * amp
        if px then
            -- свежий кусок ярче, старый тускнеет
            local f = i / n
            surface.SetDrawColor(C_DIM.r + (C_GREEN.r - C_DIM.r) * f, C_DIM.g + (C_GREEN.g - C_DIM.g) * f, C_DIM.b + (C_GREEN.b - C_DIM.b) * f, 120 + 135 * f)
            surface.DrawLine(px, py, cx, cy)
            surface.DrawLine(px, py + 1, cx, cy + 1)
        end
        px, py = cx, cy
    end
end

